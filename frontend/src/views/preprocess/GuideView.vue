    <h3>网格离散</h3>
    <p>
      计算扫描点云和 BIM 模型的差异，对构件及结构整体尺寸质量进行评估，因此需进行 BIM 的格式转换。
      本软件采用<b>泊松圆盘采样（Poisson-Disk Sampling）</b>来实现网格文件与点云文件的格式转换：
      在一个宽高分别为 w、h 的网格平面内平均生成一堆的点，且这些点之间的距离不能小于采样半径 R。
    </p>
    <ul>
      <li>输入点云：网格文件，支持后缀 stl / ply / obj / off / gltf / glb</li>
