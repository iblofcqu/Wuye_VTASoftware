    <h3>尺寸缩放</h3>
    <p>
      本软件默认单位为 m，与常用扫描仪单位一致；当采用手持扫描仪时，点云单位通常为 mm；BIM 模型单位亦存在为 m 的情况；
      可通过本模块将点云单位更改为 m / dm / cm / mm。
    </p>

    <h3>下采样</h3>
    <p>
      点云数据通常数据量庞大、数据冗余度高。为了降低计算成本，需要从大量数据点中筛选出能够较好保留数据特征的点云，
      用来替代原点云数据进行相关操作。筛选的过程就是下采样（也称降采样），其本质是将点云数据均匀化和轻量化的过程。
      本软件包含点云下采样的常用方法：<b>体素下采样、均匀下采样</b>。
    </p>
    <ul>
      <li><b>体素下采样</b>：将点云数据集所占据的三维空间划分成多个体素，以每个体素中所有点计算得到的重心作为采样点。体素尺寸越大，采样程度越高。</li>
      <li><b>均匀下采样</b>：将点云数据按照索引顺序，从第一个点开始，以固定间隔进行采样。采样间隔越大，采样程度越高。</li>
    </ul>

    <h3>配准</h3>
    <p>
      点云数据配准就是将不同坐标系中的数据点通过坐标变换的方式统一到同一坐标系中；变换过程中，通常将保持不动的点云数据称为目标点云数据，
      需要进行变换的数据称为源点云数据。点云配准实际上是寻找目标点云数据与源点云数据之间的刚性变换矩阵（旋转矩阵 R 和平移矩阵 T），以实现二者之间的最优匹配。
    </p>
    <ul>
      <li><b>粗配准（Coarse Registration）</b>：在源点云与目标点云初始相对位置未知的情况下进行粗略配准，快速估算一个大致的点云配准矩阵，为旋转矩阵 R 和平移向量 T 提供初值。本软件提供基于 <b>FPFH 特征</b>的粗配准。</li>
      <li><b>精配准（Fine Registration）</b>：在粗配准的基础上进行更精确、更细化的配准，通过迭代最近点算法（<b>ICP 算法</b>）等计算得到较为精确的解。</li>
      <li>各站点云配准请使用扫描仪自带软件。</li>
    </ul>
